"""PDF Report Generator — exports a professional report with benchmarks,
certificate analysis, migration impact, and recommendations."""

from fpdf import FPDF
import os, datetime, sys
sys.path.insert(0, os.path.join(os.path.dirname(__file__), ".."))
from src.pqc_wrapper import *

REPORT_DIR = os.path.join(os.path.dirname(__file__), "..", "reports")
os.makedirs(REPORT_DIR, exist_ok=True)

class Report(FPDF):
    def header(self):
        self.set_font("Helvetica", "B", 9)
        self.set_text_color(100, 100, 120)
        self.cell(0, 6, "PQC Migration Toolkit - Assessment Report", align="L")
        self.cell(0, 6, datetime.date.today().strftime("%B %d, %Y"), align="R", new_x="LMARGIN", new_y="NEXT")
        self.line(10, 16, 200, 16)
        self.ln(6)
    def footer(self):
        self.set_y(-12)
        self.set_font("Helvetica", "I", 7)
        self.set_text_color(150, 150, 150)
        self.cell(0, 8, f"Page {self.page_no()}/{{nb}}", align="C")
    def section(self, title):
        self.set_font("Helvetica", "B", 14)
        self.set_text_color(0, 100, 200)
        self.cell(0, 10, title, new_x="LMARGIN", new_y="NEXT")
        self.line(10, self.get_y(), 200, self.get_y())
        self.ln(3)
    def body(self, text):
        self.set_font("Helvetica", "", 10)
        self.set_text_color(30, 30, 40)
        self.multi_cell(0, 5, text)
        self.ln(2)
    def kv(self, key, val):
        self.set_font("Helvetica", "", 10)
        self.set_text_color(100, 100, 120)
        self.cell(70, 6, key)
        self.set_text_color(30, 30, 40)
        self.set_font("Helvetica", "B", 10)
        self.cell(0, 6, str(val), new_x="LMARGIN", new_y="NEXT")

def generate_report():
    pdf = Report(orientation="P", unit="mm", format="A4")
    pdf.alias_nb_pages()
    pdf.set_auto_page_break(auto=True, margin=18)

    # ── Cover ──
    pdf.add_page()
    pdf.set_fill_color(15, 15, 30)
    pdf.rect(0, 0, 210, 297, "F")
    pdf.set_y(70)
    pdf.set_font("Helvetica", "B", 26)
    pdf.set_text_color(0, 200, 255)
    pdf.cell(0, 14, "PQC Migration Toolkit", align="C", new_x="LMARGIN", new_y="NEXT")
    pdf.set_font("Helvetica", "", 16)
    pdf.cell(0, 10, "Assessment Report", align="C", new_x="LMARGIN", new_y="NEXT")
    pdf.ln(10)
    pdf.set_font("Helvetica", "", 12)
    pdf.set_text_color(200, 200, 200)
    pdf.cell(0, 8, datetime.date.today().strftime("%B %d, %Y"), align="C", new_x="LMARGIN", new_y="NEXT")
    pdf.cell(0, 8, "Post-Quantum Cryptography Readiness Assessment", align="C", new_x="LMARGIN", new_y="NEXT")
    pdf.ln(30)
    pdf.set_text_color(120, 120, 130)
    pdf.set_font("Helvetica", "I", 9)
    pdf.cell(0, 6, "Generated by the PQC Migration Toolkit", align="C", new_x="LMARGIN", new_y="NEXT")
    pdf.cell(0, 6, "100% free and open-source via kyber-py / dilithium-py / customtkinter", align="C", new_x="LMARGIN", new_y="NEXT")

    # ── Executive Summary ──
    pdf.add_page()
    pdf.section("1. Executive Summary")
    pdf.body("This report assesses an organization's readiness for post-quantum cryptography (PQC) migration. "
             "It provides benchmark data, certificate size comparisons, migration impact analysis, and "
             "actionable recommendations for transitioning from classical (RSA/ECC) to post-quantum "
             "(ML-KEM/ML-DSA) cryptographic algorithms.")
    pdf.body(f"Report generated: {datetime.datetime.now().strftime('%Y-%m-%d %H:%M')}")
    pdf.body(f"Python version: {sys.version.split()[0]}")
    pdf.body("The assessment covers three NIST-standardized PQC algorithms: ML-KEM (FIPS 203) for key "
             "encapsulation and ML-DSA (FIPS 204) for digital signatures, implemented using pure Python "
             "libraries for educational and evaluation purposes.")

    # ── Benchmark Results ──
    pdf.add_page()
    pdf.section("2. Performance Benchmarks")
    pdf.body("Average operation timing in milliseconds (5 runs per operation, pure Python). "
             "Note: Optimized C (liboqs) is typically 50-100x faster.")
    pdf.ln(3)
    # RSA + ECC
    pdf.set_font("Helvetica", "B", 11)
    pdf.set_text_color(200, 50, 50)
    pdf.cell(0, 8, "Classical Algorithms", new_x="LMARGIN", new_y="NEXT")
    from src.pqc_wrapper import measure_full_rsa, measure_full_ecc, describe_stats
    for label, fn in [("RSA-2048", lambda: measure_full_rsa(5)), ("ECDSA P-256", lambda: measure_full_ecc(5))]:
        r = fn()
        for op, vals in r.items():
            avg, _, _, _ = describe_stats(vals)
            pdf.body(f"  {label} {op}: avg={avg:.1f}ms")

    for cat, algos, fn in [
        ("ML-KEM (Key Encapsulation)", ["ML-KEM-512", "ML-KEM-768", "ML-KEM-1024"], measure_full_kem),
        ("ML-DSA (Digital Signatures)", ["ML-DSA-44", "ML-DSA-65", "ML-DSA-87"], measure_full_sig),
    ]:
        pdf.set_font("Helvetica", "B", 11)
        pdf.set_text_color(0, 100, 200)
        pdf.cell(0, 8, cat, new_x="LMARGIN", new_y="NEXT")
        for name in algos:
            r = fn(name, 5)
            for op, vals in r.items():
                avg, mn, mx, std = describe_stats(vals)
                pdf.body(f"  {name} {op}: avg={avg:.1f}ms  min={mn:.1f}  max={mx:.1f}  std={std:.1f}")

    # ── Certificate Size Comparison ──
    pdf.add_page()
    pdf.section("3. Certificate Size Comparison")
    pdf.body("Classical vs post-quantum key sizes. PQC keys are 3-10x larger than classical equivalents.")
    pdf.ln(3)
    pdf.set_font("Courier", "", 9)
    pdf.set_text_color(30, 30, 40)
    data = []
    for algo, label in [
        (lambda: rsa.generate_private_key(65537, 2048), "RSA-2048"),
        (lambda: rsa.generate_private_key(65537, 4096), "RSA-4096"),
        (lambda: ec.generate_private_key(ec.SECP256R1()), "ECDSA P-256"),
    ]:
        key = algo()
        cert = make_self_signed_cert(key)
        sz = len(cert.public_bytes(serialization.Encoding.PEM))
        data.append((label, f"{sz} bytes", "Classical"))
    for name in ["ML-DSA-65", "ML-DSA-87"]:
        pk, sk = sig_keygen(name)
        data.append((f"{name} pubkey", f"{len(pk)} bytes", "Post-Quantum"))
    pdf.body("  Type                          Size            Era")
    pdf.body("  " + "-" * 55)
    for typ, sz, era in data:
        pdf.body(f"  {typ:30s} {sz:>15s}  {era}")

    # ── Security Dashboard Summary ──
    pdf.add_page()
    pdf.section("4. Quantum Safety Assessment")
    pdf.kv("RSA-2048", "Quantum-Safe: NO - Risk: 98%")
    pdf.kv("ECDSA P-256", "Quantum-Safe: NO - Risk: 95%")
    pdf.kv("ML-KEM-768", "Quantum-Safe: YES - Security: 192-bit (NIST Level 3)")
    pdf.kv("ML-DSA-65", "Quantum-Safe: YES - Security: 192-bit (NIST Level 3)")
    pdf.ln(5)
    pdf.body("Conclusion: Organizations still relying solely on RSA or ECC face significant risk from "
             "quantum attacks. Hybrid deployments (classical + PQC) are recommended immediately.")

    # ── Hybrid TLS Results ──
    pdf.add_page()
    pdf.section("5. Hybrid TLS 1.3 (X25519 + ML-KEM-768)")
    try:
        c_key, s_key, stats = hybrid_tls()
        match = "MATCH" if c_key == s_key else "MISMATCH"
        pdf.kv("Client X25519 pubkey", f"{stats['client_pub_x25519']} bytes")
        pdf.kv("Client ML-KEM pubkey", f"{stats['client_pub_kem']} bytes")
        pdf.kv("Server X25519 pubkey", f"{stats['server_pub_x25519']} bytes")
        pdf.kv("Ciphertext size", f"{stats['ct_size']} bytes")
        pdf.kv("Session key match", match)
        pdf.kv("Total handshake size", f"{stats['client_pub_x25519'] + stats['client_pub_kem'] + stats['ct_size']} bytes")
        pdf.ln(3)
        pdf.body("Hybrid TLS combines classical (X25519) and post-quantum (ML-KEM) key exchange in a single "
                 "handshake. This is the same approach used by Google Chrome since 2024.")
    except Exception as e:
        pdf.body(f"TLS handshake test: {e}")

    # ── Hybrid Certificate Chain ──
    pdf.add_page()
    pdf.section("6. Hybrid Certificate Chain")
    try:
        from src.hybrid_cert import generate_hybrid_chain
        text, chain_stats = generate_hybrid_chain()
        pdf.kv("Root CA size", f"{chain_stats['root_size']} bytes + {chain_stats['mldsa_root_sig']}B sig")
        pdf.kv("Intermediate CA size", f"{chain_stats['inter_size']} bytes + {chain_stats['mldsa_inter_sig']}B sig")
        pdf.kv("Leaf cert size", f"{chain_stats['leaf_size']} bytes + {chain_stats['mldsa_leaf_sig']}B sig")
        total = chain_stats['root_size'] + chain_stats['inter_size'] + chain_stats['leaf_size']
        pdf.kv("Total chain size", f"{total} bytes (vs ~3KB classical)")
        pdf.ln(3)
        pdf.body("Each certificate in the chain carries BOTH a classical (RSA) signature and a "
                 "post-quantum (ML-DSA) signature. This ensures backward compatibility while "
                 "providing quantum resistance.")
    except Exception as e:
        pdf.body(f"Chain generation: {e}")

    # ── Migration Impact Analysis ──
    pdf.add_page()
    pdf.section("7. Migration Impact Analysis")
    from src.impact_calc import calculate
    text, impact_data = calculate()
    pdf.kv("Classical cert storage", f"{impact_data['classical_storage']/1024/1024:.1f} MB")
    pdf.kv("Hybrid cert storage", f"{impact_data['hybrid_storage']/1024/1024:.1f} MB")
    pdf.kv("Extra storage required", f"{impact_data['extra_storage']/1024/1024:.1f} MB")
    pdf.kv("Extra bandwidth/month", f"{impact_data['extra_monthly']/1024/1024/1024:.2f} GB")
    pdf.ln(5)
    pdf.body("The additional bandwidth cost of hybrid TLS is generally acceptable for modern networks. "
             "The main challenge is software/hardware compatibility, not raw data transfer.")

    # ── Attack Demo Summary ──
    pdf.add_page()
    pdf.section("8. Harvest Now Decrypt Later (HNDL)")
    pdf.body("The HNDL attack demonstrates why immediate migration is critical:")
    pdf.body("1. Adversary records encrypted traffic today (classical RSA/ECC).")
    pdf.body("2. Quantum computers mature in 5-10 years.")
    pdf.body("3. Stored ciphertexts are decrypted retroactively.")
    pdf.body("4. Long-lived secrets (classified docs, trade secrets) are exposed.")
    pdf.ln(3)
    pdf.body("PQC algorithms like ML-KEM and ML-DSA resist quantum attacks because "
             "lattice problems are hard for both classical and quantum computers.")
    pdf.set_font("Helvetica", "B", 11)
    pdf.set_text_color(200, 0, 0)
    pdf.cell(0, 8, "Risk: REAL. Timeline: NOW. Action: MIGRATE.", new_x="LMARGIN", new_y="NEXT")

    # ── Recommendations ──
    pdf.add_page()
    pdf.section("9. Recommendations")
    recs = [
        "1. Start cryptographic inventory immediately. Know what algorithms and key sizes you use.",
        "2. Prioritize systems with long-lived secrets (certificate authorities, document signing, email).",
        "3. Deploy hybrid certificates (RSA + ML-DSA) for all new certificates.",
        "4. Enable hybrid TLS (X25519 + ML-KEM) on all web servers and CDNs.",
        "5. Monitor NIST, IETF, and CA/Browser Forum for updated PQC standards.",
        "6. Budget for a 3-5 year migration timeline.",
        "7. Use tools like the PQC Migration Toolkit for testing and evaluation.",
    ]
    for r in recs:
        pdf.body(r)
    pdf.ln(5)
    pdf.set_font("Helvetica", "B", 11)
    pdf.set_text_color(0, 150, 50)
    pdf.cell(0, 8, "The time to prepare for post-quantum cryptography is now.", new_x="LMARGIN", new_y="NEXT")
    pdf.cell(0, 8, "Harvest Now, Decrypt Later is a real threat to long-lived secrets.", new_x="LMARGIN", new_y="NEXT")

    path = os.path.join(REPORT_DIR, f"PQC_Report_{datetime.date.today().isoformat()}.pdf")
    pdf.output(path)
    return path
